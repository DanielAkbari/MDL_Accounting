export interface COA {
  no: string;
  type: string;
  code: string;
  name: string;
  parentCode?: string;
  isCustom?: boolean;
  project?: 'Pariwisata' | 'Properti' | 'Umum';
}

export function getCoaProject(code: string, name: string): 'Pariwisata' | 'Properti' | 'Umum' {
  const c = code;
  const n = (name || '').toLowerCase();
  
  if (n.includes('pariwisata') || n.includes('glamping') || n.includes('cabin') || n.includes('villa') || n.includes('dreamcamp') || n.includes('wahana') || n.includes('atv') || n.includes('skuter') || n.includes('seluncuran') || n.includes('ayunan') || n.includes('sultan') || n.includes('foodcourt') || n.includes('breakfast') || n.includes('laundry') || n.includes('mdl') || n.includes('dreamrun')) {
    return 'Pariwisata';
  }
  if (n.includes('properti') || n.includes('kavling') || n.includes('bphtb') || n.includes('ajb') || n.includes('notaris') || n.includes('patok')) {
    return 'Properti';
  }

  if (c.startsWith('113') || c.startsWith('411') || c.startsWith('511') || c.startsWith('61102') || c.startsWith('61104')) {
    return 'Properti';
  }
  if (c.startsWith('112') || c.startsWith('421') || c.startsWith('431') || c.startsWith('521') || c.startsWith('61103') || c.startsWith('61105')) {
    return 'Pariwisata';
  }
  if (c.startsWith('62220') || c.startsWith('62221') || c.startsWith('63330') || c.startsWith('61110') || c.startsWith('431281')) {
    return 'Pariwisata';
  }
  
  return 'Umum';
}

