export const getMergedCOA = (): COA[] => {
  if (typeof window === 'undefined') return cleanAndReclassifyCoas(COA_LIST);
  
  // One-time reset to clear any colliding/corrupt custom CoAs from previous sessions
  const resetFlag = 'mdl_coa_reset_v5';
  if (localStorage.getItem(resetFlag) !== 'true') {
    localStorage.removeItem('coa_list');
    localStorage.removeItem('custom_coa');
    localStorage.setItem(resetFlag, 'true');
  }
  
  let masterCoas: COA[] = [];
  const saved = localStorage.getItem('coa_list');
  if (saved) {
    masterCoas = JSON.parse(saved);
  } else {
    // Filter out any default bank accounts from COA_LIST
    // (type === 'BANK' or starting with '11' except '1105')
    const defaultBankCodes = ['11206', '11202', '11308', '11005', '11208', '11200', '11300'];
    const filtered = COA_LIST.filter(c => c.type !== 'BANK' && !defaultBankCodes.includes(c.code));
    
    // Add new Bank Accounts
    const newBanks: COA[] = [
      { no: 'bank-parent', type: 'BANK', code: '11000', name: 'Kas & Bank', parentCode: undefined, project: 'Umum' },
      { no: 'bank-sub-1', type: 'BANK', code: '11101', name: 'BCA Pariwisata', parentCode: '11000', project: 'Pariwisata' },
      { no: 'bank-sub-2', type: 'BANK', code: '11102', name: 'BCA Dreamcamp', parentCode: '11000', project: 'Pariwisata' },
      { no: 'bank-sub-3', type: 'BANK', code: '11103', name: 'BCA Properti', parentCode: '11000', project: 'Properti' },
      { no: 'bank-sub-4', type: 'BANK', code: '11104', name: 'Mandiri Properti', parentCode: '11000', project: 'Properti' },
      { no: 'bank-sub-5', type: 'BANK', code: '11105', name: 'Kas Kasir', parentCode: '11000', project: 'Pariwisata' },
      { no: 'bank-sub-6', type: 'BANK', code: '11106', name: 'Kas Operasional Pariwisata', parentCode: '11000', project: 'Pariwisata' },
      { no: 'bank-sub-7', type: 'BANK', code: '11107', name: 'Kas Operasional Properti', parentCode: '11000', project: 'Properti' },
    ];
    masterCoas = [...filtered, ...newBanks];
    localStorage.setItem('coa_list', JSON.stringify(masterCoas));
  }

  // Sync custom CoAs from 'custom_coa' (backup restore or transactions page additions)
  const customSaved = localStorage.getItem('custom_coa');
  if (customSaved) {
    try {
      const customCoas: COA[] = JSON.parse(customSaved);
      if (Array.isArray(customCoas)) {
        let listChanged = false;
        customCoas.forEach(custom => {
          if (!masterCoas.some(c => c.code === custom.code)) {
            masterCoas.push(custom);
            listChanged = true;
          }
        });
        if (listChanged) {
          localStorage.setItem('coa_list', JSON.stringify(masterCoas));
        }
      }
    } catch (e) {
      console.error('Error parsing custom_coa:', e);
    }
  }
  
  return cleanAndReclassifyCoas(masterCoas);
};

