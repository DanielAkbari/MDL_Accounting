export function migrateTransactionsBankAccounts(transactions: any[]): { updated: any[]; modified: boolean } {
  let modified = false;
  const updated = transactions.map(t => {
    let code = t.accountCode || '';
    let name = t.accountName || '';
    let actId = t.accountId || '';
    let changed = false;

    // 1. Migrate Account Code & Name
    if (code === '11206') { // BCA DreamRun
      code = '11102'; // BCA Dreamcamp
      name = 'BCA Dreamcamp';
      changed = true;
    } else if (code === '11202') { // BCA Pariwisata
      code = '11101'; // BCA Pariwisata
      name = 'BCA Pariwisata';
      changed = true;
    } else if (code === '11308') { // BCA Properti
      code = '11103'; // BCA Properti
      name = 'BCA Properti';
      changed = true;
    } else if (code === '11208') { // BSI
      code = '11101'; // BCA Pariwisata
      name = 'BCA Pariwisata';
      changed = true;
    } else if (code === '11200') { // Bank Pariwisata
      code = '11000'; // Kas & Bank
      name = 'Kas & Bank';
      changed = true;
    } else if (code === '11300') { // Bank Properti
      code = '11000'; // Kas & Bank
      name = 'Kas & Bank';
      changed = true;
    } else if (code === '11005') { // BCAS Operasional
      const isProperti = t.project === 'Properti' || 
                         (t.unit && (t.unit.toLowerCase().includes('kavling') || t.unit.toLowerCase().includes('properti')));
      if (isProperti) {
        code = '11107'; // Kas Operasional Properti
        name = 'Kas Operasional Properti';
      } else {
        code = '11106'; // Kas Operasional Pariwisata
        name = 'Kas Operasional Pariwisata';
      }
      changed = true;
    } else if (code === '1000') {
      code = '11000';
      name = 'Kas & Bank';
      changed = true;
    }

    // 2. Migrate Account ID (Bank Account ID)
    if (actId === '11206') { // BCA DreamRun -> BCA Dreamcamp
      actId = '11102';
      changed = true;
    } else if (actId === '11202') { // BCA Pariwisata -> BCA Pariwisata
      actId = '11101';
      changed = true;
    } else if (actId === '11308') { // BCA Properti -> BCA Properti
      actId = '11103';
      changed = true;
    } else if (actId === '11208') { // BSI -> BCA Pariwisata
      actId = '11101';
      changed = true;
    } else if (actId === '11200') { // Bank Pariwisata -> Kas & Bank
      actId = '11000';
      changed = true;
    } else if (actId === '11300') { // Bank Properti -> Kas & Bank
      actId = '11000';
      changed = true;
    } else if (actId === '11005') { // BCAS Operasional
      const isProperti = t.project === 'Properti' || 
                         (t.unit && (t.unit.toLowerCase().includes('kavling') || t.unit.toLowerCase().includes('properti')));
      if (isProperti) {
        actId = '11107'; // Kas Operasional Properti
      } else {
        actId = '11106'; // Kas Operasional Pariwisata
      }
      changed = true;
    } else if (actId === '1000') {
      actId = '11000';
      changed = true;
    }

    if (changed) {
      modified = true;
      return { ...t, accountCode: code, accountName: name, accountId: actId };
    }
    return t;
  });

  return { updated, modified };
}
